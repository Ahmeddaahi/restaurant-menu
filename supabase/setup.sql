-- Run this once in the new project's Supabase SQL Editor.
begin;

create table if not exists public.categories (
    id text primary key,
    name_en text not null,
    name_so text not null,
    image_url text
);

create table if not exists public.menu_items (
    id text primary key default gen_random_uuid()::text,
    name_en text not null,
    name_so text not null,
    category_id text references public.categories(id) on update cascade on delete set null,
    price numeric(10, 2) not null check (price >= 0),
    image_url text,
    description_en text,
    description_so text,
    is_popular boolean not null default false,
    rating numeric(2, 1) not null default 0 check (rating >= 0 and rating <= 5),
    prep_time text,
    created_at timestamptz not null default now()
);

create table if not exists public.reviews (
    id bigint generated by default as identity primary key,
    rating smallint not null check (rating between 1 and 5),
    name text,
    feedback text check (feedback is null or char_length(feedback) <= 500),
    hidden boolean not null default false,
    created_at timestamptz not null default now()
);

alter table public.categories enable row level security;
alter table public.menu_items enable row level security;
alter table public.reviews enable row level security;

grant usage on schema public to anon, authenticated;
grant select on public.categories, public.menu_items, public.reviews to anon;
grant insert on public.reviews to anon;
grant select, insert, update, delete on public.categories, public.menu_items, public.reviews to authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

drop policy if exists categories_public_read on public.categories;
create policy categories_public_read on public.categories
    for select to anon, authenticated using (true);
drop policy if exists categories_admin_manage on public.categories;
create policy categories_admin_manage on public.categories
    for all to authenticated using (true) with check (true);

drop policy if exists menu_items_public_read on public.menu_items;
create policy menu_items_public_read on public.menu_items
    for select to anon, authenticated using (true);
drop policy if exists menu_items_admin_manage on public.menu_items;
create policy menu_items_admin_manage on public.menu_items
    for all to authenticated using (true) with check (true);

drop policy if exists reviews_public_read on public.reviews;
create policy reviews_public_read on public.reviews
    for select to anon, authenticated using (hidden = false);
drop policy if exists reviews_public_submit on public.reviews;
create policy reviews_public_submit on public.reviews
    for insert to anon, authenticated with check (hidden = false);
drop policy if exists reviews_admin_manage on public.reviews;
create policy reviews_admin_manage on public.reviews
    for all to authenticated using (true) with check (true);

insert into public.categories (id, name_en, name_so) values
