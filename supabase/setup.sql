    ('Food', 'Food', 'Cunto'),
    ('Snacks', 'Snacks', 'Cunto Fudud'),
    ('Desserts', 'Desserts', 'Macmacaan')
on conflict (id) do nothing;

insert into public.menu_items (
    id, name_en, name_so, category_id, price, image_url,
    description_en, description_so, is_popular, rating, prep_time
) values (
